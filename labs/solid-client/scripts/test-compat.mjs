import assert from "node:assert/strict";
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { root } from "./project.mjs";
import { runCoreCompatibility } from "../tooling/run-core-compat.mjs";

const result = runCoreCompatibility();
assert.equal(result.success, true, "LilScript compatibility cases failed");

writeFileSync(
  resolve(root, "artifacts/lilscript-compat.json"),
  `${JSON.stringify(result, null, 2)}\n`,
);

const modeRows = result.runs
  .map(
    ({ mode, backend, generatedBytes, passed, failed }) =>
      `| ${mode} | ${backend} | ${generatedBytes} | ${passed} | ${failed} |`,
  )
  .join("\n");
const caseRows = result.cases
  .map(
    ({ id, name, group, passed }) =>
      `| ${id} | ${name} | ${group} | ${passed ? "pass" : "fail"} |`,
  )
  .join("\n");
const markdown = `# LilScript Solid runtime compatibility

The same ${result.uniqueCases} behavior ports execute with maximum optimization
and with all optional optimizations disabled on the JavaScript runtime target.
This is ${result.executions} total compiler/runtime executions against a
469-test upstream target. C/native portability is a separate compiler concern:
those targets do not yet implement the JavaScript exception and Promise
semantics required by Solid's public API.

| Mode | Backend | Generated bytes | Passed | Failed |
| --- | --- | ---: | ---: | ---: |
${modeRows}

| ID | Behavior | Group | Result |
| ---: | --- | --- | --- |
${caseRows}
`;
writeFileSync(resolve(root, "artifacts/lilscript-compat.md"), markdown);

console.log(
  `LilScript runtime compatibility passed: ${result.passed}/${result.uniqueCases} cases in ${result.executions} backend/mode executions.`,
);
