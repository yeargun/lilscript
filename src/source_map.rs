pub(crate) enum OriginKind {
    Function,
    Global,
    Parameter,
    Local,
    Temporary,
    Instruction,
    Property,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct Origin {
    span: Span,
    name: Option<String>,
    kind: OriginKind,
}

/// Token provenance after the selected emitter output has been composed
/// through all final JavaScript-only rewrites. Source maps and analysis maps
/// consume this same object so enabling both never repeats tokenization/diff
/// composition.
pub(crate) struct ComposedJavaScriptProvenance {
    analysis: crate::js_peephole::GeneratedJavaScriptSourceMapAnalysis,
    origins: Vec<Option<Origin>>,
}

/// Reuses line tables and normalized source paths while an analysis sidecar
/// resolves many generated/source locations. Source Map v3 already batches
/// this work; the analysis-map path needs random access because decisions are
/// ordered semantically rather than by generated byte offset.
pub(crate) struct DebugPositionIndex<'a> {
    generated: &'a str,
    generated_line_starts: Vec<usize>,
    modules: &'a ModuleSet,
    source_paths: Vec<String>,
    source_line_starts: Vec<Vec<usize>>,
}

impl<'a> DebugPositionIndex<'a> {
    pub(crate) fn new(
        generated: &'a str,
        modules: &'a ModuleSet,
        source_base: Option<&Path>,
    ) -> Self {
        Self {
            generated,
            generated_line_starts: line_starts(generated),
            modules,
            source_paths: modules
                .modules
                .iter()
                .map(|module| source_path(&module.path, source_base))
                .collect(),
            source_line_starts: modules
                .modules
                .iter()
                .map(|module| line_starts(&module.source))
                .collect(),
        }
    }

    pub(crate) fn generated(&self, offset: usize) -> (u32, u32) {
        byte_position(self.generated, &self.generated_line_starts, offset)
    }

    pub(crate) fn source(&self, span: Span) -> (String, u32, u32) {
        let (source_id, local_span) = locate_linked_span_index(self.modules, span);
        let module = &self.modules.modules[source_id];
        let (line, column) = byte_position(
            &module.source,
            &self.source_line_starts[source_id],
            local_span.start,
        );
        (self.source_paths[source_id].clone(), line, column)
    }

    pub(crate) fn source_path(&self, source_id: usize) -> &str {
        &self.source_paths[source_id]
    }
}

