#[serde(rename_all = "camelCase")]
struct MangledNameRecord {
    generated: String,
    original: String,
    source: String,
    line: u32,
    column: u32,
    kind: OriginKind,
    occurrences: usize,
}

pub(crate) fn compose_javascript_provenance(
    generated: &str,
    trace: &IrJsSourceTrace,
    witness: Option<&JavaScriptArtifactWitness>,
    modules: &ModuleSet,
) -> Result<ComposedJavaScriptProvenance, SourceMapBuildError> {
    let raw_analysis =
        analyze_generated_javascript_for_source_map(&trace.code).map_err(|error| {
            SourceMapBuildError(format!("cannot tokenize traced JavaScript: {error}"))
        })?;
    let final_analysis =
        analyze_generated_javascript_for_source_map(generated).map_err(|error| {
            SourceMapBuildError(format!("cannot tokenize selected JavaScript: {error}"))
        })?;
    let raw_tokens = &raw_analysis.tokens;
    let final_tokens = &final_analysis.tokens;
    let mut final_origins = if final_tokens.is_empty() {
        Vec::new()
    } else {
        let mut raw_origins = origins_for_raw_tokens(trace, raw_tokens)?;
        apply_raw_binding_origins(
            trace,
            modules,
            raw_tokens,
            &raw_analysis.bindings,
            &mut raw_origins,
        );
        let raw_exact_keys = token_keys(raw_tokens, &raw_analysis.bindings, true);
        let final_exact_keys = token_keys(final_tokens, &final_analysis.bindings, true);
        let raw_generic_keys = token_keys(raw_tokens, &raw_analysis.bindings, false);
        let final_generic_keys = token_keys(final_tokens, &final_analysis.bindings, false);
        compose_origins(
            &trace.code,
            generated,
            raw_tokens,
            final_tokens,
            &raw_exact_keys,
            &final_exact_keys,
            &raw_generic_keys,
            &final_generic_keys,
            &raw_origins,
        )
    };
    if !final_tokens.is_empty() {
        apply_trace_property_origins(
            trace,
            modules,
            final_tokens,
            &final_analysis.properties,
            &mut final_origins,
        );
        if let Some(witness) = witness {
            apply_property_origins(witness, modules, final_tokens, &mut final_origins);
        }
        stabilize_final_binding_origins(
            modules,
            final_tokens,
            &final_analysis.bindings,
            &mut final_origins,
        );
        fill_unmapped_origins(&mut final_origins);
    }
    Ok(ComposedJavaScriptProvenance {
        analysis: final_analysis,
        origins: final_origins,
    })
}

pub(crate) fn build_javascript_source_map_from_provenance(
    generated: &str,
    composed: &ComposedJavaScriptProvenance,
    modules: &ModuleSet,
    source_base: Option<&Path>,
    include_sources_content: bool,
) -> Result<JavaScriptSourceMap, SourceMapBuildError> {
    let final_tokens = &composed.analysis.tokens;
    let final_origins = &composed.origins;
    if final_tokens.is_empty() {
        return build_empty_source_map(modules, source_base, include_sources_content);
    }

    let generated_positions =
        byte_positions_for_sorted_offsets(generated, final_tokens.iter().map(|token| token.start));
    let source_indices = modules
        .modules
        .iter()
        .map(|module| SourceIndex {
            path: source_path(&module.path, source_base),
            line_starts: line_starts(&module.source),
        })
        .collect::<Vec<_>>();
    let mut builder = SourceMapBuilder::new(None);
    for (module, index) in modules.modules.iter().zip(&source_indices) {
        let source_id = builder.add_source(&index.path);
        if include_sources_content {
            builder.set_source_contents(source_id, Some(&module.source));
        }
    }

    let mut mangled = BTreeMap::<(String, String, String, u32, u32, OriginKind), usize>::new();
    let property_names = composed
        .analysis
        .properties
        .iter()
        .map(|property| (property.start, property.name.clone()))
        .collect::<BTreeMap<_, _>>();
    let mut mapping_count = 0usize;
    let mut names = BTreeSet::new();
    let mut source_position_cache = BTreeMap::new();
    for ((token, origin), (generated_line, generated_column)) in final_tokens
        .iter()
        .zip(final_origins)
        .zip(generated_positions)
    {
        let Some(origin) = origin else {
            continue;
        };
        let (source_id, local_span) = locate_linked_span_index(modules, origin.span);
        let module = &modules.modules[source_id];
        let source_index = &source_indices[source_id];
        let source_offset = local_span.start.min(module.source.len());
        let (source_line, source_column) = *source_position_cache
            .entry((source_id, source_offset))
            .or_insert_with(|| {
                byte_position(&module.source, &source_index.line_starts, source_offset)
            });
        let original_name = origin.name.as_deref().filter(|_| {
            token.kind == GeneratedJavaScriptTokenKind::Identifier
                || origin.kind == OriginKind::Property && property_names.contains_key(&token.start)
        });
        builder.add(
            generated_line,
            generated_column,
            source_line,
            source_column,
            Some(&source_index.path),
            original_name,
            false,
        );
        mapping_count += 1;
        if let Some(name) = original_name {
            names.insert(name.to_string());
            let emitted_name = if origin.kind == OriginKind::Property {
                property_names.get(&token.start).map(String::as_str)
            } else {
                (token.kind == GeneratedJavaScriptTokenKind::Identifier)
                    .then_some(token.text.as_str())
            };
            if let Some(emitted_name) = emitted_name.filter(|emitted| *emitted != name) {
                *mangled
                    .entry((
                        emitted_name.to_string(),
                        name.to_string(),
                        source_index.path.clone(),
                        source_line,
                        source_column,
                        origin.kind,
                    ))
                    .or_default() += 1;
            }
        }
    }

    let map = builder.into_sourcemap();
    let mut encoded = Vec::new();
    map.to_writer(&mut encoded)
        .map_err(|error| SourceMapBuildError(format!("cannot encode source map: {error}")))?;
    let mut json: serde_json::Value = serde_json::from_slice(&encoded)
        .map_err(|error| SourceMapBuildError(format!("cannot extend source map JSON: {error}")))?;
    let mangled = mangled
        .into_iter()
        .map(
            |((generated, original, source, line, column, kind), occurrences)| MangledNameRecord {
                generated,
                original,
                source,
                line,
                column,
                kind,
                occurrences,
            },
        )
        .collect::<Vec<_>>();
    json.as_object_mut()
        .expect("Source Map v3 is a JSON object")
        .insert(
            "x_lilscript".to_string(),
            serde_json::json!({
                "version": 1,
                "mappingModel": "selected-artifact-token-provenance",
                "sourcesContentIncluded": include_sources_content,
                "mangledNames": mangled,
                "notes": [
                    "Mappings describe code that survived optimization; eliminated source has no generated position.",
                    "One generated binding can represent several non-overlapping SSA values after local-name coalescing."
                ]
            }),
        );
    let json = serde_json::to_string(&json)
        .map_err(|error| SourceMapBuildError(format!("cannot serialize source map: {error}")))?;
    Ok(JavaScriptSourceMap {
        json,
        data_url: OnceLock::new(),
        sources: source_indices.len(),
        mappings: mapping_count,
        original_names: names.len(),
    })
}

pub(crate) fn selected_name_records(
    composed: &ComposedJavaScriptProvenance,
) -> Vec<SelectedNameRecord> {
    let property_names = composed
        .analysis
        .properties
        .iter()
        .map(|property| (property.start, property.name.as_str()))
        .collect::<BTreeMap<_, _>>();
    let mut records = BTreeMap::<(String, String, Span, OriginKind), (usize, usize)>::new();
    for (token, origin) in composed.analysis.tokens.iter().zip(&composed.origins) {
        let Some(origin) = origin else {
            continue;
        };
        let Some(original) = origin.name.as_deref() else {
            continue;
        };
        let emitted = if origin.kind == OriginKind::Property {
            property_names.get(&token.start).copied()
        } else if token.kind == GeneratedJavaScriptTokenKind::Identifier {
            Some(token.text.as_str())
        } else {
            None
        };
        let Some(emitted) = emitted else {
            continue;
        };
        let entry = records
            .entry((
                emitted.to_string(),
                original.to_string(),
                origin.span,
                origin.kind,
            ))
            .or_insert((0, token.start));
        entry.0 += 1;
        entry.1 = entry.1.min(token.start);
    }
    records
        .into_iter()
        .map(
            |((generated, original, span, kind), (occurrences, first_generated))| {
                SelectedNameRecord {
                    generated,
                    original,
                    span,
                    kind,
                    occurrences,
                    first_generated,
                }
            },
        )
        .collect()
}

fn apply_trace_property_origins(
    trace: &IrJsSourceTrace,
    modules: &ModuleSet,
    tokens: &[GeneratedJavaScriptTokenOccurrence],
    properties: &[GeneratedJavaScriptPropertyOccurrence],
    origins: &mut [Option<Origin>],
) {
    let mut by_emitted = BTreeMap::<&str, Vec<&IrJsPropertyProvenance>>::new();
    for provenance in &trace.properties {
        by_emitted
            .entry(&provenance.emitted)
            .or_default()
            .push(provenance);
    }
    for candidates in by_emitted.values_mut() {
        candidates.sort_by_key(|candidate| match candidate.category {
            IrJsPropertyCategory::Owned => 0,
            IrJsPropertyCategory::External => 1,
            IrJsPropertyCategory::Unowned => 2,
        });
    }
    for property in properties {
        let Ok(index) = tokens.binary_search_by_key(&property.start, |token| token.start) else {
            continue;
        };
        let Some(candidates) = by_emitted.get(property.name.as_str()) else {
            continue;
        };
        let contextual = origins[index].as_ref().and_then(|origin| {
            candidates.iter().find_map(|candidate| {
                source_name_span_within(modules, origin.span, &candidate.source)
                    .map(|span| (*candidate, span))
            })
        });
        let Some((provenance, span)) = contextual.or_else(|| {
            let provenance = candidates.first().copied()?;
            let span = provenance
                .span
                .map(|span| narrow_span_to_source_name(modules, span, &provenance.source))
                .or_else(|| {
                    find_source_name_span(
                        modules,
                        provenance.owner.as_deref(),
                        provenance.source.as_str(),
                    )
                })?;
            Some((provenance, span))
        }) else {
            continue;
        };
        origins[index] = Some(Origin {
            span,
            name: Some(provenance.source.clone()),
            kind: OriginKind::Property,
        });
    }
}

fn build_empty_source_map(
    modules: &ModuleSet,
    source_base: Option<&Path>,
    include_sources_content: bool,
) -> Result<JavaScriptSourceMap, SourceMapBuildError> {
    let mut builder = SourceMapBuilder::new(None);
    for module in &modules.modules {
        let id = builder.add_source(&source_path(&module.path, source_base));
        if include_sources_content {
            builder.set_source_contents(id, Some(&module.source));
        }
    }
    let map = builder.into_sourcemap();
    let mut encoded = Vec::new();
    map.to_writer(&mut encoded)
        .map_err(|error| SourceMapBuildError(format!("cannot encode source map: {error}")))?;
    let mut json: serde_json::Value = serde_json::from_slice(&encoded)
        .map_err(|error| SourceMapBuildError(format!("cannot extend source map JSON: {error}")))?;
    json.as_object_mut()
        .expect("Source Map v3 is a JSON object")
        .insert(
            "x_lilscript".to_string(),
            serde_json::json!({
                "version": 1,
                "mappingModel": "selected-artifact-token-provenance",
                "sourcesContentIncluded": include_sources_content,
                "mangledNames": [],
                "notes": [
                    "The selected JavaScript artifact is empty, so it has no generated mappings."
                ]
            }),
        );
    let json = serde_json::to_string(&json)
        .map_err(|error| SourceMapBuildError(format!("cannot serialize source map: {error}")))?;
    Ok(JavaScriptSourceMap {
        json,
        data_url: OnceLock::new(),
        sources: modules.modules.len(),
        mappings: 0,
        original_names: 0,
    })
}

fn origins_for_raw_tokens(
    trace: &IrJsSourceTrace,
    tokens: &[GeneratedJavaScriptTokenOccurrence],
) -> Result<Vec<Option<Origin>>, SourceMapBuildError> {
    let mut anchors = trace.anchors.clone();
    anchors.sort_by_key(|anchor| anchor.generated);
    let mut origins = vec![None; tokens.len()];
    let mut anchor_index = 0usize;
    let mut current = None;
    for (token_index, token) in tokens.iter().enumerate() {
        while anchors
            .get(anchor_index)
            .is_some_and(|anchor| anchor.generated <= token.start)
        {
            current = anchors.get(anchor_index).map(origin_from_anchor);
            anchor_index += 1;
        }
        if current.is_none() {
            while let Some(anchor) = anchors.get(anchor_index) {
                if anchor.generated <= token.end {
                    current = Some(origin_from_anchor(anchor));
                    anchor_index += 1;
                } else {
                    break;
                }
            }
        }
        origins[token_index] = current.clone();
    }
    Ok(origins)
}

fn origin_from_anchor(anchor: &IrJsSourceAnchor) -> Origin {
    Origin {
        span: anchor.span,
        name: anchor.original_name.clone(),
        kind: if anchor.original_name.is_some() {
            OriginKind::Temporary
        } else {
            OriginKind::Instruction
        },
    }
}

fn apply_raw_binding_origins(
    trace: &IrJsSourceTrace,
    modules: &ModuleSet,
    tokens: &[GeneratedJavaScriptTokenOccurrence],
    occurrences: &[GeneratedJavaScriptBindingOccurrence],
    origins: &mut [Option<Origin>],
) {
    let mut by_declaration = BTreeMap::<usize, Origin>::new();
    for occurrence in occurrences.iter().filter(|occurrence| {
        occurrence.kind == GeneratedJavaScriptBindingKind::Bound
            && occurrence.declaration_start == Some(occurrence.start)
    }) {
        let owner = trace
            .function_regions
            .iter()
            .filter(|region| {
                occurrence.start >= region.generated_start
                    && occurrence.start < region.generated_end
            })
            .min_by_key(|region| region.generated_end.saturating_sub(region.generated_start))
            .map(|region| region.function);
        if let Some(binding) = select_binding_provenance(&trace.bindings, owner, occurrence) {
            by_declaration.insert(
                occurrence.start,
                Origin {
                    span: narrow_span_to_source_name(modules, binding.span, &binding.source),
                    name: Some(binding.source.clone()),
                    kind: binding_kind(binding.category),
                },
            );
        }
    }
    for occurrence in occurrences {
        let Some(declaration) = occurrence.declaration_start else {
            continue;
        };
        let Some(mut origin) = by_declaration.get(&declaration).cloned() else {
            continue;
        };
        if let Ok(index) = tokens.binary_search_by_key(&occurrence.start, |token| token.start) {
            if let Some(span) = origins[index].as_ref().and_then(|current| {
                origin
                    .name
                    .as_deref()
                    .and_then(|name| source_name_span_within(modules, current.span, name))
            }) {
                origin.span = span;
            }
            origins[index] = Some(origin);
        }
    }
}

fn select_binding_provenance<'a>(
    provenance: &'a [IrJsBindingProvenance],
    owner: Option<crate::ir::FunctionId>,
    occurrence: &crate::js_peephole::GeneratedJavaScriptBindingOccurrence,
) -> Option<&'a IrJsBindingProvenance> {
    let mut candidates = provenance
        .iter()
        .filter(|binding| binding.emitted == occurrence.name)
        .filter(|binding| binding.function == owner || binding.function.is_none())
        .collect::<Vec<_>>();
    candidates.sort_by(|left, right| {
        (
            binding_owner_rank(left.function, owner),
            left.category,
            left.span.start,
            &left.source,
        )
            .cmp(&(
                binding_owner_rank(right.function, owner),
                right.category,
                right.span.start,
                &right.source,
            ))
    });
    candidates
        .iter()
        .copied()
        .find(|binding| binding.source == occurrence.name)
        .or_else(|| candidates.first().copied())
}

fn binding_owner_rank(
    candidate: Option<crate::ir::FunctionId>,
    owner: Option<crate::ir::FunctionId>,
) -> u8 {
    if candidate == owner {
        0
    } else {
        1
    }
}

const fn binding_kind(category: IrJsBindingCategory) -> OriginKind {
    match category {
        IrJsBindingCategory::Function => OriginKind::Function,
        IrJsBindingCategory::Global => OriginKind::Global,
        IrJsBindingCategory::Parameter => OriginKind::Parameter,
        IrJsBindingCategory::Local => OriginKind::Local,
        IrJsBindingCategory::Temporary => OriginKind::Temporary,
    }
}

fn token_keys(
    tokens: &[GeneratedJavaScriptTokenOccurrence],
    bindings: &[GeneratedJavaScriptBindingOccurrence],
    retain_bound_spelling: bool,
) -> Vec<TokenKey> {
    let by_range = bindings
        .iter()
        .map(|binding| {
            (
                (binding.start, binding.end),
                (
                    binding.kind,
                    binding.declaration_start == Some(binding.start),
                ),
            )
        })
        .collect::<BTreeMap<_, _>>();
    tokens
        .iter()
        .map(|token| match by_range.get(&(token.start, token.end)) {
            Some((GeneratedJavaScriptBindingKind::Bound, declaration)) => {
                TokenKey::BoundIdentifier {
                    spelling: retain_bound_spelling.then(|| token.text.clone()),
                    declaration: *declaration,
                }
            }
            _ => TokenKey::Exact(token.kind, token.text.clone()),
        })
        .collect()
}

#[allow(clippy::too_many_arguments)]
fn compose_origins(
    raw_source: &str,
    final_source: &str,
    raw_tokens: &[GeneratedJavaScriptTokenOccurrence],
    final_tokens: &[GeneratedJavaScriptTokenOccurrence],
    raw_exact_keys: &[TokenKey],
    final_exact_keys: &[TokenKey],
    raw_generic_keys: &[TokenKey],
    final_generic_keys: &[TokenKey],
    raw_origins: &[Option<Origin>],
) -> Vec<Option<Origin>> {
    if raw_source == final_source && raw_tokens.len() == final_tokens.len() {
        return raw_origins.to_vec();
    }
    let mut origins = vec![None; final_tokens.len()];
    transfer_equal_origins(raw_exact_keys, final_exact_keys, raw_origins, &mut origins);
    transfer_equal_origins(
        raw_generic_keys,
        final_generic_keys,
        raw_origins,
        &mut origins,
    );
    origins
}

fn transfer_equal_origins(
    raw_keys: &[TokenKey],
    final_keys: &[TokenKey],
    raw_origins: &[Option<Origin>],
    origins: &mut [Option<Origin>],
) {
    for operation in capture_diff_slices(Algorithm::Histogram, raw_keys, final_keys) {
        let DiffOp::Equal {
            old_index,
            new_index,
            len,
        } = operation
        else {
            continue;
        };
        for offset in 0..len {
            if origins[new_index + offset].is_none() {
                origins[new_index + offset] = raw_origins[old_index + offset].clone();
            }
        }
    }
}

fn stabilize_final_binding_origins(
    modules: &ModuleSet,
    tokens: &[GeneratedJavaScriptTokenOccurrence],
    occurrences: &[GeneratedJavaScriptBindingOccurrence],
    origins: &mut [Option<Origin>],
) {
    let mut by_declaration = BTreeMap::<usize, Vec<usize>>::new();
    for occurrence in occurrences {
        if occurrence.kind != GeneratedJavaScriptBindingKind::Bound {
            continue;
        }
        let Some(declaration) = occurrence.declaration_start else {
            continue;
        };
        if let Ok(index) = tokens.binary_search_by_key(&occurrence.start, |token| token.start) {
            by_declaration.entry(declaration).or_default().push(index);
        }
    }
    for (declaration, indices) in by_declaration {
        let declaration_origin = tokens
            .binary_search_by_key(&declaration, |token| token.start)
            .ok()
            .and_then(|index| origins[index].clone())
            .filter(|origin| {
                matches!(
                    origin.kind,
                    OriginKind::Function
                        | OriginKind::Global
                        | OriginKind::Parameter
                        | OriginKind::Local
                        | OriginKind::Temporary
                ) && origin.name.is_some()
            });
        let origin = declaration_origin.or_else(|| {
            indices
                .iter()
                .filter_map(|index| origins[*index].as_ref())
                .find(|origin| origin.name.is_some())
                .cloned()
        });
        let Some(origin) = origin else {
            continue;
        };
        for index in indices {
            let mut stabilized = origin.clone();
            if let Some(span) = origins[index].as_ref().and_then(|current| {
                stabilized
                    .name
                    .as_deref()
                    .and_then(|name| source_name_span_within(modules, current.span, name))
            }) {
                stabilized.span = span;
            }
            origins[index] = Some(stabilized);
        }
    }
}

fn apply_property_origins(
    witness: &JavaScriptArtifactWitness,
    modules: &ModuleSet,
    tokens: &[GeneratedJavaScriptTokenOccurrence],
    origins: &mut [Option<Origin>],
) {
    for property in &witness.properties {
        if property.category != "static" {
            continue;
        }
        let Some(identity) = preferred_property_identity(property) else {
            continue;
        };
        let Some(span) =
            find_source_name_span(modules, identity.owner.as_deref(), identity.source.as_str())
        else {
            continue;
        };
        if let Ok(index) = tokens.binary_search_by_key(&property.start, |token| token.start) {
            if origins[index]
                .as_ref()
                .is_some_and(|origin| origin.kind == OriginKind::Property)
            {
                continue;
            }
            origins[index] = Some(Origin {
                span,
                name: Some(identity.source.clone()),
                kind: OriginKind::Property,
            });
        }
    }
}

fn preferred_property_identity(
    property: &JavaScriptPropertyOccurrenceWitness,
) -> Option<&crate::compiler::JavaScriptPropertyIdentityWitness> {
    property
        .identities
        .iter()
        .find(|identity| identity.owner.is_some())
        .or_else(|| property.identities.first())
}

fn find_source_name_span(modules: &ModuleSet, owner: Option<&str>, name: &str) -> Option<Span> {
    for module in &modules.modules {
        let search_start = owner
            .and_then(|owner| find_identifier(&module.source, owner, 0))
            .unwrap_or(0);
        if let Some(start) = find_identifier(&module.source, name, search_start) {
            return Some(Span::new(
                module.offset.saturating_add(start),
                module
                    .offset
                    .saturating_add(start)
                    .saturating_add(name.len()),
            ));
        }
    }
    None
}

fn narrow_span_to_source_name(modules: &ModuleSet, span: Span, name: &str) -> Span {
    source_name_span_within(modules, span, name).unwrap_or(span)
}

fn source_name_span_within(modules: &ModuleSet, span: Span, name: &str) -> Option<Span> {
    let (source_id, local_span) = locate_linked_span_index(modules, span);
    let module = &modules.modules[source_id];
    let search_end = local_span
        .end
        .max(local_span.start.saturating_add(name.len()))
        .min(module.source.len());
    let start = find_identifier_in_range(&module.source, name, local_span.start, search_end)?;
    let end = start.saturating_add(name.len());
    if end > search_end {
        return None;
    }
    Some(Span::new(
        module.offset.saturating_add(start),
        module.offset.saturating_add(end),
    ))
}

fn find_identifier(source: &str, name: &str, from: usize) -> Option<usize> {
    find_identifier_in_range(source, name, from, source.len())
}

fn find_identifier_in_range(
    source: &str,
    name: &str,
    from: usize,
    through: usize,
) -> Option<usize> {
    let from = from.min(source.len());
    let through = through.min(source.len()).max(from);
    source
        .get(from..through)?
        .match_indices(name)
        .find_map(|(relative, _)| {
            let start = from.saturating_add(relative);
            let end = start.saturating_add(name.len());
            let before = source[..start].chars().next_back();
            let after = source[end..].chars().next();
            (!before.is_some_and(is_identifier_continue)
                && !after.is_some_and(is_identifier_continue))
            .then_some(start)
        })
}

fn is_identifier_continue(character: char) -> bool {
    character == '_' || character == '$' || character.is_alphanumeric()
}

fn fill_unmapped_origins(origins: &mut [Option<Origin>]) {
    let mut current = None;
    for origin in origins.iter_mut() {
        if origin.is_some() {
            current.clone_from(origin);
        } else if current.is_some() {
            origin.clone_from(&current);
        }
    }
    let mut current = None;
    for origin in origins.iter_mut().rev() {
        if origin.is_some() {
            current.clone_from(origin);
        } else if current.is_some() {
            origin.clone_from(&current);
        }
    }
}

fn source_path(path: &Path, base: Option<&Path>) -> String {
    let resolved_base = base.and_then(|base| base.canonicalize().ok());
    let path = resolved_base
        .as_deref()
        .and_then(|base| path.strip_prefix(base).ok())
        .unwrap_or(path);
    path.to_string_lossy().replace('\\', "/")
}

fn locate_linked_span_index(modules: &ModuleSet, span: Span) -> (usize, Span) {
    let source_id = modules
        .modules
        .partition_point(|module| module.offset <= span.start)
        .checked_sub(1)
        .unwrap_or(modules.root);
    let module = &modules.modules[source_id];
    (
        source_id,
        Span::new(
            span.start
                .saturating_sub(module.offset)
                .min(module.source.len()),
            span.end
                .saturating_sub(module.offset)
                .min(module.source.len()),
        ),
    )
}

fn line_starts(source: &str) -> Vec<usize> {
    let mut starts = vec![0];
    starts.extend(
        source
            .bytes()
            .enumerate()
            .filter_map(|(index, byte)| (byte == b'\n').then_some(index + 1)),
    );
    starts
}

fn byte_position(source: &str, line_starts: &[usize], offset: usize) -> (u32, u32) {
    let offset = offset.min(source.len());
    let line = line_starts
        .partition_point(|start| *start <= offset)
        .saturating_sub(1);
    let line_start = line_starts.get(line).copied().unwrap_or(0);
    let column = source[line_start..offset]
        .chars()
        .map(char::len_utf16)
        .sum::<usize>();
    (
        u32::try_from(line).unwrap_or(u32::MAX),
        u32::try_from(column).unwrap_or(u32::MAX),
    )
}

fn byte_positions_for_sorted_offsets(
    source: &str,
    offsets: impl IntoIterator<Item = usize>,
) -> Vec<(u32, u32)> {
    let mut positions = Vec::new();
    let mut cursor = 0usize;
    let mut line = 0u32;
    let mut column = 0u32;
    for offset in offsets {
        let offset = offset.min(source.len()).max(cursor);
        for character in source[cursor..offset].chars() {
            if character == '\n' {
                line = line.saturating_add(1);
                column = 0;
            } else {
                column = column.saturating_add(character.len_utf16() as u32);
            }
        }
        positions.push((line, column));
        cursor = offset;
    }
    positions
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn reports_utf16_columns() {
        let source = "a😀b\nç";
        let starts = line_starts(source);
        assert_eq!(byte_position(source, &starts, "a😀".len()), (0, 3));
        assert_eq!(byte_position(source, &starts, source.len()), (1, 1));
        assert_eq!(
            byte_positions_for_sorted_offsets(source, [0, 1, 5, 6, 7, source.len()]),
            vec![(0, 0), (0, 1), (0, 3), (0, 4), (1, 0), (1, 1)]
        );
    }

    #[test]
    fn finds_only_complete_identifiers() {
        assert_eq!(
            find_identifier("total subtotal total2 total", "total", 0),
            Some(0)
        );
        assert_eq!(
            find_identifier("subtotal total2 total", "total", 0),
            Some(16)
        );
    }

    #[test]
    fn absolute_source_paths_keep_one_root_separator() {
        #[cfg(unix)]
        assert_eq!(
            source_path(Path::new("/project/src/main.lil"), None),
            "/project/src/main.lil"
        );
    }
}
