#[derive(Debug, Clone, PartialEq, Eq, Hash, PartialOrd, Ord)]
enum TokenKey {
    BoundIdentifier {
        spelling: Option<String>,
        declaration: bool,
    },
    Exact(GeneratedJavaScriptTokenKind, String),
}

#[derive(Debug, Clone)]
struct SourceIndex {
    path: String,
    line_starts: Vec<usize>,
}

