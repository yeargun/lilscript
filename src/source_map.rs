/// A standard Source Map v3 artifact plus summary information useful to build
/// systems. The JavaScript itself is deliberately not stored here: hidden-map
/// builds can prove that enabling this artifact did not alter one program byte.
#[derive(Debug, Clone)]
pub struct JavaScriptSourceMap {
    json: String,
    data_url: OnceLock<String>,
    sources: usize,
    mappings: usize,
    original_names: usize,
}

impl JavaScriptSourceMap {
    pub fn as_str(&self) -> &str {
        &self.json
    }

    pub fn data_url(&self) -> &str {
        self.data_url.get_or_init(|| {
            format!(
                "data:application/json;charset=utf-8;base64,{}",
                base64::engine::general_purpose::STANDARD.encode(self.json.as_bytes())
            )
        })
    }

    pub const fn source_count(&self) -> usize {
        self.sources
    }

    pub const fn mapping_count(&self) -> usize {
        self.mappings
    }

    pub const fn original_name_count(&self) -> usize {
        self.original_names
    }
}

impl PartialEq for JavaScriptSourceMap {
    fn eq(&self, other: &Self) -> bool {
        self.json == other.json
            && self.sources == other.sources
            && self.mappings == other.mappings
            && self.original_names == other.original_names
    }
}

impl Eq for JavaScriptSourceMap {}

#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct SourceMapBuildError(pub String);

impl std::fmt::Display for SourceMapBuildError {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        formatter.write_str(&self.0)
    }
}

impl std::error::Error for SourceMapBuildError {}

