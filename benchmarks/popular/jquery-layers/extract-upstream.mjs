import { readFileSync } from "node:fs";
import { dirname, join, posix } from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "acorn";
import { jqueryVersion, layerById } from "./catalog.mjs";

function visit(node, callback) {
  if (!node || typeof node !== "object") {
    return;
  }
  callback(node);
  for (const [key, value] of Object.entries(node)) {
    if (["start", "end", "loc", "range"].includes(key)) {
      continue;
    }
    if (Array.isArray(value)) {
      for (const child of value) {
        visit(child, callback);
      }
    } else if (value && typeof value === "object") {
      visit(value, callback);
    }
  }
}

function defineCall(program) {
  let found = null;
  visit(program, (node) => {
    if (
      found ||
      node.type !== "CallExpression" ||
      node.callee.type !== "Identifier" ||
      node.callee.name !== "define"
    ) {
      return;
    }
    found = node;
  });
  if (!found) {
    throw new Error("expected a define() factory");
  }
  return found;
}

function resolveDep(fromFile, spec) {
  return posix.normalize(posix.join(posix.dirname(fromFile), spec)) + ".js";
}

function emitFactory(source, factory, binding) {
  if (factory.body.type !== "BlockStatement") {
    throw new Error(`${binding}: expected a block factory`);
  }
  const statements = factory.body.body.filter(
    (statement) =>
      !(
        statement.type === "ExpressionStatement" &&
        statement.directive === "use strict"
      ),
  );
  if (statements.length === 0) {
    throw new Error(`${binding}: empty factory`);
  }
  const last = statements[statements.length - 1];
  if (last.type !== "ReturnStatement") {
    return statements
      .map((statement) => source.slice(statement.start, statement.end))
      .join("\n");
  }
  if (!last.argument) {
    throw new Error(`${binding}: factory must return a value`);
  }
  const argument = last.argument;
  if (argument.type === "FunctionExpression") {
    const name = argument.id?.name ?? binding;
    const params = argument.params.length
      ? source.slice(
          argument.params[0].start,
          argument.params[argument.params.length - 1].end,
        )
      : "";
    const body = source.slice(argument.body.start, argument.body.end);
    return `function ${name}(${params})${body}`;
  }
  if (argument.type === "Identifier" && argument.name === binding) {
    const prefix = statements
      .slice(0, -1)
      .map((statement) => source.slice(statement.start, statement.end))
      .join("\n");
    return prefix;
  }
  const prefix = statements
    .slice(0, -1)
    .map((statement) => source.slice(statement.start, statement.end))
    .join("\n");
  const expr = source.slice(argument.start, argument.end);
  const assign = `var ${binding} = ${expr};`;
  return prefix ? `${prefix}\n${assign}` : assign;
}

export function extractLayerSource(layer, upstreamRoot) {
  const chunks = [
    `// Extracted from jquery ${jqueryVersion} src for layer ${layer.id}.`,
    `// Regenerated by extract-upstream.mjs. Do not edit by hand.`,
  ];
  const emitted = new Set();
  for (const { file, binding } of layer.upstreamFiles) {
    const path = join(upstreamRoot, file);
    const source = readFileSync(path, "utf8");
    const program = parse(source, { ecmaVersion: "latest", sourceType: "script" });
    const call = defineCall(program);
    const factory = call.arguments.find(
      (argument) =>
        argument.type === "FunctionExpression" ||
        argument.type === "ArrowFunctionExpression",
    );
    if (!factory) {
      throw new Error(`${file}: define() factory not found`);
    }
    const deps = call.arguments[0]?.type === "ArrayExpression"
      ? call.arguments[0].elements.map((element) => {
          if (element?.type !== "Literal" || typeof element.value !== "string") {
            throw new Error(`${file}: expected string define() dependency`);
          }
          return resolveDep(file, element.value);
        })
      : [];
    for (const dep of deps) {
      if (!layer.upstreamFiles.some((entry) => entry.file === dep)) {
        throw new Error(`${file} depends on ${dep}, which is not in layer ${layer.id}`);
      }
    }
    chunks.push(`\n// --- jquery/src/${file} ---`);
    chunks.push(emitFactory(source, factory, binding).trim());
    emitted.add(binding);
    for (const snippet of layer.afterBindings ?? []) {
      if (snippet.after === binding) {
        chunks.push(`\n// --- jquery/src/${snippet.source} (${snippet.note}) ---`);
        chunks.push(snippet.code.trim());
      }
    }
  }
  for (const name of layer.exports) {
    if (!emitted.has(name)) {
      throw new Error(`layer ${layer.id} exports ${name} but never bound it`);
    }
  }
  chunks.push(`\nexport { ${layer.exports.join(", ")} };\n`);
  return chunks.join("\n");
}

export function extractLayer(id, upstreamRoot) {
  return extractLayerSource(layerById(id), upstreamRoot);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const labRoot = dirname(fileURLToPath(import.meta.url));
  const id = process.argv[2];
  if (!id) {
    throw new Error("usage: node extract-upstream.mjs <layer-id>");
  }
  process.stdout.write(extractLayer(id, join(labRoot, "../node_modules/jquery/src")));
}
