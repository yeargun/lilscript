#!/usr/bin/env python3
"""Reproduce the pinned native text library amalgamations; no compiler output edits.

Upstream files stay byte-identical. Local includes are expanded in place (including
both opcode expansions). Public declarations acquire internal linkage, so the
library neither exports symbols nor retains unused entry points. Diagnostics are
isolated to the vendor body; generated source and providers retain strict warnings.
"""
from pathlib import Path
import hashlib
import json
import re

root = Path(__file__).resolve().parents[1]
vendor = root / 'third_party/quickjs'
manifest = json.loads((vendor / 'manifest.json').read_text())
for name, digest in manifest['files'].items():
    assert hashlib.sha256((vendor / name).read_bytes()).hexdigest() == digest, name

def source(name):
    text = (vendor / name).read_text()
    if name == 'libunicode.c':
        text = text.replace('uint8_t const lre_ctype_bits[256] =',
                            'static uint8_t const lre_ctype_bits[256] =')
    if name == 'libregexp.c':
        # This file-private table also occurs in libunicode.c. Keep the two
        # translation-unit namespaces separate in their combined C recipe.
        text = re.sub(r'\bchar_range_s\b', 'ls_regex_char_range_s', text)
    if name.endswith('.h') and name not in ('libregexp-opcode.h', 'libunicode-table.h'):
        # Only column-zero function declarations have these return prefixes.
        text = re.sub(r'^(?=(?:void|char|int|uint8_t|const char)\b[^;\n]*\()',
                      'static LS_NATIVE_UNUSED ', text, flags=re.M)
        text = text.replace('extern uint8_t const lre_ctype_bits[256];',
                            'static uint8_t const lre_ctype_bits[256];')
    def include(match):
        child = match[1]
        if child in ('libregexp-opcode.h', 'libunicode-table.h'):
            return source(child) + f'\n#line {text[:match.end()].count(chr(10)) + 2} "quickjs/{name}"'
        assert child in manifest['files'], child
        return '/* supplied by the preceding amalgamated header */'
    text = re.sub(r'^#include "([^"]+)"', include, text, flags=re.M)
    return f'#line 1 "quickjs/{name}"\n' + text

def write(name, files):
    body = ('/* Generated by scripts/vendor-native-text.py from QuickJS '
            + manifest['revision'] + '. MIT license follows. */\n'
            '#if defined(__GNUC__)\n#pragma GCC diagnostic push\n'
            '#pragma GCC diagnostic ignored "-Wunused-parameter"\n'
            '#pragma GCC diagnostic ignored "-Wsign-compare"\n'
            '#pragma GCC diagnostic ignored "-Wunused-function"\n#endif\n')
    body += '\n'.join(source(file) for file in files)
    body += '\n#if defined(__GNUC__)\n#pragma GCC diagnostic pop\n#endif\n'
    body += f'#line 1 "lilscript/{name}"\n'
    (root / 'src/program/runtime' / name).write_text(body)

write('unicode-library.c', ['cutils.h', 'libunicode.h', 'cutils.c', 'libunicode.c'])
write('regex-library.c', ['libregexp.h', 'libregexp.c'])
