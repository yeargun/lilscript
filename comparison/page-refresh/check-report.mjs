import assert from 'node:assert/strict';
import { writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
const {chromium}=await import(pathToFileURL('/home/azureuser/katexlil/node_modules/playwright/index.mjs'));
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000},offline:true});
const errors=[];
page.on('pageerror',error=>errors.push(String(error)));
await page.goto(pathToFileURL(process.argv[2]).href);
assert.equal(await page.locator('article.card').count(),27);
assert.equal(await page.locator('#motion-performance').count(),1);
const evidence=await page.locator('#evidence').evaluate(el=>JSON.parse(el.textContent));
const blocked=evidence.libraries.filter(row=>row.sourceBuild.status!=='complete').length;
await page.selectOption('#status','blocked');
assert.equal(await page.locator('article.card:visible').count(),blocked);
await page.selectOption('#status','all');
await page.fill('#filter','Zod');
assert.equal(await page.locator('article.card:visible').count(),1);
await page.fill('#filter','');
const download=page.waitForEvent('download');
await page.click('#download');
assert.equal((await download).suggestedFilename(),'lilscript-source-build-evidence.json');
await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));
await page.screenshot({path:process.argv[3]+'/report-preview.png'});
await page.setViewportSize({width:390,height:844});
await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));
const dimensions=await page.evaluate(()=>({width:innerWidth,content:document.documentElement.scrollWidth}));
assert.ok(dimensions.content<=dimensions.width,JSON.stringify(dimensions));
await page.screenshot({path:process.argv[3]+'/report-mobile.png'});
assert.deepEqual(errors,[]);
writeFileSync(process.argv[3]+'/report-checks.json',JSON.stringify({offline:true,libraries:27,blockedFilter:blocked,search:true,evidenceDownload:true,mobile:dimensions,pageErrors:errors},null,2)+'\n');
await browser.close();
console.log('Report passed offline rendering, filters, evidence download, and mobile layout checks.');
